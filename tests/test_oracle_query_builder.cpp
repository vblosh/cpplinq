TEST(OracleConnectionTest, FactoryAndMetadataWithoutOpening) {
    auto conn = make_connection<oracle>("OracleDSN");
    ASSERT_NE(conn, nullptr);
    EXPECT_FALSE(conn->is_open());
    EXPECT_NE(dynamic_cast<OracleConnection*>(conn.get()), nullptr);

    // info() falls back to static defaults until the ODBC handle is opened.
    const DriverInfo info = conn->info();
    EXPECT_EQ(info.driver_name, "Oracle ODBC Driver");
    EXPECT_EQ(info.dbms_name, "Oracle");
    EXPECT_TRUE(info.driver_version.empty());
    EXPECT_TRUE(info.dbms_version.empty());
    EXPECT_TRUE(info.odbc_version.empty());

    const DriverCapabilities caps = conn->capabilities();
    EXPECT_TRUE(caps.cancel);
    EXPECT_TRUE(caps.streaming);
    EXPECT_TRUE(caps.query_timeout);
    EXPECT_TRUE(caps.transactions);
    // Reported for the built-in drivers, but no savepoint API consumes the flag.
    EXPECT_TRUE(caps.savepoints);
    EXPECT_FALSE(caps.returning_clause);
    EXPECT_FALSE(caps.output_clause);
    EXPECT_TRUE(caps.upsert);
    EXPECT_FALSE(caps.array_batch_insert);
    EXPECT_EQ(caps.default_batch_chunk_size, 1000u);
    EXPECT_TRUE(caps.window_functions);
    EXPECT_TRUE(caps.ctes);
}

